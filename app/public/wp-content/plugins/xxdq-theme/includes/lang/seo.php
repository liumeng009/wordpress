<?php
/**
 * XXDQ i18n — language-aware SEO templates.
 *
 * Yoast stores its title / description templates per post type and per
 * taxonomy in the `wpseo_titles` option. Those templates are a single
 * set of strings shared by every language, so on the English site they
 * inject Chinese text into the <title> and leave the meta description
 * empty.
 *
 * This module keeps Yoast as the single SEO emit engine (per the
 * site's existing policy) but overrides the templates per language:
 *
 *   - On the Chinese site the stored Yoast templates are used as-is,
 *     so nothing changes.
 *   - On the English site the templates are replaced with English
 *     equivalents, and any empty description template gets a real
 *     English description.
 *
 * The per-term descriptions that live in `wp_yoast_indexable` are
 * regenerated by the English content builder, so taxonomy archives get
 * a proper English meta description as well.
 *
 * @package XXDQ
 */

if (!defined('ABSPATH')) exit;

class XXDQ_I18n_Seo {

    /**
     * The English SEO templates, keyed by the Yoast option name.
     *
     * @return array
     */
    public static function en_templates() {
        /* The catalogue size is computed from the database so the copy
         * can never drift away from the real product list. */
        $cat = function_exists('xxdq_catalogue_kw') ? xxdq_catalogue_kw() : '300';

        return [
            /* ── Product taxonomy ─────────────────────────────── */
            'title-tax-product_category'  => '%%term_title%% - Manufacturer | Gengwen Electric',
            'metadesc-tax-product_category' => '%%term_description%%',

            /* ── Product archive ──────────────────────────────── */
            'title-ptarchive-product'    => 'Electrical Connectors & Terminals - Manufacturer | Gengwen Electric',
            'metadesc-ptarchive-product' => 'Gengwen Electric manufactures copper lugs, crimp terminals, pre-insulated terminals, connectors and wire-end accessories. ' . $cat . '+ models in stock, CE / RoHS / ISO9001 certified, factory direct supply, 1-hour quotation.',
            'social-title-ptarchive-product' => 'Electrical Connectors & Terminals | Gengwen Electric',
            'social-description-ptarchive-product' => 'Copper lugs, crimp terminals, pre-insulated terminals and connectors from a direct manufacturer in Yueqing, China.',

            /* ── News archive ─────────────────────────────────── */
            'title-ptarchive-news'       => 'News & Industry Insights | Gengwen Electric',
            'metadesc-ptarchive-news'    => 'Selection guides, crimping standards and factory news for copper lugs, crimp terminals, pre-insulated terminals and other electrical connectors.',
            'social-title-ptarchive-news' => 'News & Industry Insights | Gengwen Electric',
            'social-description-ptarchive-news' => 'Industry selection experience, crimping process standards and factory updates.',

            /* ── Homepage ─────────────────────────────────────── */
            'title-home'                 => 'Electrical Connector Manufacturer | Copper Lugs & Crimp Terminals',
            'metadesc-home'              => 'Gengwen Electric is a Yueqing-based manufacturer of copper lugs, crimp terminals, pre-insulated terminals and electrical connectors. ' . $cat . '+ models in stock, CE / RoHS / ISO9001 certified, 24-hour dispatch, 1-hour quotation. OEM / ODM welcome.',

            /* ── Products ─────────────────────────────────────── */
            'title-product'              => '%%title%% | Copper Lug & Crimp Terminal Manufacturer',
            'metadesc-product'           => '%%excerpt%%',
            'social-title-product'       => '%%title%%',
            'social-description-product' => '%%excerpt%%',
        ];
    }

    /**
     * Apply the English templates on the English site.
     */
    public static function init() {
        add_filter('wpseo_titles', [__CLASS__, 'filter_titles'], 20);
    }

    /**
     * Rewrite Yoast's template set for the English site.
     *
     * @param array $titles Yoast's title/description template array.
     * @return array
     */
    public static function filter_titles($titles) {
        if (!XXDQ_I18n::is_en()) {
            return $titles;
        }
        if (!is_array($titles)) {
            return $titles;
        }

        foreach (self::en_templates() as $key => $value) {
            $titles[$key] = $value;
        }

        return $titles;
    }

    /**
     * Ensure the English site always emits an ENGLISH meta description.
     *
     * Two problems are handled here:
     *
     * 1. Yoast omits the tag entirely when it has nothing to say. The
     *    English pages have no Yoast indexable row of their own (Yoast
     *    only indexed the Chinese originals), so their description came
     *    out empty.
     *
     * 2. Yoast's indexable for the shared archives/products still holds
     *    the CHINESE description, which Yoast serves verbatim on the
     *    English site. Any description that still contains Chinese
     *    characters is replaced with an English one.
     *
     * @param string $description The description Yoast resolved.
     * @return string
     */
    public static function ensure_metadesc($description) {
        $is_en = XXDQ_I18n::is_en();

        $fallback = $is_en
            ? self::en_description_fallback()
            : self::zh_description_fallback();

        /* No context to build a fallback from — leave Yoast's value. */
        if ($fallback === '') {
            return $description;
        }

        $description = (string) $description;

        /* On the Chinese site the taxonomy archives are ALWAYS rebuilt
         * from the term. The stored Yoast per-term description
         * (`wpseo_taxonomy_meta`) held a single hand-edited entry that
         * had drifted into a 196-character run of half-sentences, and
         * the template `metadesc-tax-product_category` was empty for
         * every other term — so most Chinese category pages rendered
         * NO meta description at all. Generating the description from
         * the term makes all of them consistent and correct. */
        if (!$is_en && self::is_taxonomy_archive()) {
            return $fallback;
        }

        /* Empty → always use the fallback. */
        if (trim($description) === '') {
            return $fallback;
        }

        /* On the English site a Chinese description is a leak from the
         * shared indexable row and must be replaced. On the Chinese
         * site Chinese is the correct language, so it stays. */
        if ($is_en && self::has_cjk($description)) {
            return $fallback;
        }

        /* A description that is too long gets truncated by the search
         * engine anyway — cut it here, on a sentence boundary, so the
         * snippet reads cleanly. */
        if ($is_en && mb_strlen($description) > 300) {
            return self::en_trim_description($description);
        }

        /* A description that is too short wastes the snippet. Some
         * Chinese articles have an empty excerpt, so Yoast falls back
         * to the title — 28 characters is not a description. */
        if (!$is_en && mb_strlen($description) < 70 && $fallback !== '') {
            return $fallback;
        }

        return $description;
    }

    /**
     * Trim an English description to the snippet window.
     *
     * @param string $description The description.
     * @return string
     */
    private static function en_trim_description($description) {
        $cut = mb_substr($description, 0, 300);

        /* Prefer a sentence end. */
        $dot = mb_strrpos($cut, '. ');
        if ($dot !== false && $dot > 120) {
            return mb_substr($cut, 0, $dot + 1);
        }

        /* Otherwise cut on a comma. */
        $comma = mb_strrpos($cut, ', ');
        if ($comma !== false && $comma > 120) {
            return mb_substr($cut, 0, $comma) . '.';
        }

        return rtrim($cut, " \t\n\r.,;:") . '.';
    }

    /**
     * Is the current request a taxonomy archive?
     *
     * @return bool
     */
    private static function is_taxonomy_archive() {
        return is_tax() || is_category() || is_tag();
    }

    /**
     * Build a Chinese meta description for the current request.
     *
     * Yoast's taxonomy template `metadesc-tax-product_category` is
     * empty in the site's Yoast options, so the Chinese category
     * archives rendered NO meta description tag at all — a hard SEO
     * defect on ~95 indexable pages. The description is therefore
     * assembled here from the term itself.
     *
     * The term description is used as the base because it already
     * carries the series list and the size range, but it holds
     * embedded HTML (an <img> tag on the top-level categories) that
     * must be stripped before it goes into a meta tag.
     *
     * @return string Empty when no context could be determined.
     */
    private static function zh_description_fallback() {
        if (is_tax() || is_category() || is_tag()) {
            $term = get_queried_object();
            if (!is_object($term)) {
                return '';
            }

            $name = (string) $term->name;
            if ($name === '') {
                return '';
            }

            /* Strip the HTML the term description carries. */
            $body = wp_strip_all_tags((string) $term->description, true);
            $body = trim(preg_replace('/\s+/u', ' ', $body));

            /* The count is the number of published products in the term. */
            $count = isset($term->count) ? (int) $term->count : 0;

            $lead = $count > 0
                ? sprintf('%s 全系列 %d 款现货', $name, $count)
                : $name . ' 全系列';

            $tail = '国标规格，CE/RoHS 认证，源头工厂直发，支持批量询价与 OEM/ODM 定制。';

            if ($body !== '') {
                $body = self::zh_trim_copy($body, 70);

                /* The copy must end on a full stop, otherwise it runs
                 * straight into the closing clause. */
                if (!preg_match('/[。.!?]$/u', $body)) {
                    $body .= '。';
                }
                return $lead . '：' . $body . $tail;
            }

            return $lead . '。' . $tail;
        }

        /* Chinese articles: Yoast falls back to the TITLE when the
         * article has no excerpt, which is far too short for a search
         * snippet (one title was 28 characters). The article's first
         * paragraph is used instead. */
        if (is_singular('news')) {
            $excerpt = trim((string) get_post_field('post_excerpt', get_the_ID()));
            if ($excerpt !== '') {
                return self::zh_trim_copy($excerpt, 150);
            }

            $content = (string) get_post_field('post_content', get_the_ID());
            $content = wp_strip_all_tags($content, true);
            $content = trim(preg_replace('/\s+/u', ' ', $content));

            if ($content !== '') {
                return self::zh_trim_copy($content, 150);
            }
        }

        return '';
    }

    /**
     * Trim Chinese marketing copy to a length budget on a clean break.
     *
     * The category descriptions are written as a series of short
     * clauses separated by "，" and closed with "。". Cutting them at
     * an arbitrary character produces broken text such as
     * "适配 1.25–…" or "配电柜、电力、", which reads badly in a
     * search result. This helper cuts on the last full stop inside the
     * budget and falls back to the last comma, and never leaves a
     * dangling separator behind.
     *
     * @param string $text   The copy to trim.
     * @param int    $budget Maximum number of characters.
     * @return string
     */
    private static function zh_trim_copy($text, $budget) {
        $text = trim((string) $text);
        if (mb_strlen($text) <= $budget) {
            return $text;
        }

        $cut = mb_substr($text, 0, $budget);

        /* Prefer a full stop — it ends a sentence. */
        $dot = mb_strrpos($cut, '。');
        if ($dot !== false && $dot >= 20) {
            return mb_substr($cut, 0, $dot + 1);
        }

        /* Otherwise break on the last comma — the Chinese copy uses
         * both the full-width "，" and the half-width ",". */
        $comma = -1;
        foreach (array('，', ',', '、') as $sep) {
            $pos = mb_strrpos($cut, $sep);
            if ($pos !== false && $pos > $comma) {
                $comma = $pos;
            }
        }
        if ($comma >= 20) {
            return mb_substr($cut, 0, $comma);
        }

        /* A single long clause with no separator — cut it, but drop a
         * trailing separator character so the sentence stays clean. */
        $body = rtrim($cut, '，,、-–— ');
        return $body;
    }

    /**
     * Does the string contain Chinese characters?
     *
     * @param string $text Text to test.
     * @return bool
     */
    private static function has_cjk($text) {
        return is_string($text) && (bool) preg_match('/[\x{4e00}-\x{9fff}]/u', $text);
    }

    /**
     * The model code of a product, taken from its title.
     *
     * The English product titles carry the code either as an
     * alphanumeric token ("DT-25 Tinned Copper Oil-Block Terminal") or
     * as a series in brackets ("Oil-Block Copper Terminal (DT Series)").
     *
     * @param string $title The product title.
     * @return string Empty when the title has no code.
     */
    private static function model_code_from_title($title) {
        $title = (string) $title;

        /* "DT-25 …" */
        if (preg_match('/\b([A-Za-z]{1,5}[-–]?\d{1,4}[A-Za-z0-9\-]*)\b/u', $title, $m)) {
            return $m[1];
        }

        /* "… (DT Series)" / "… (TZ-JTK Series)" */
        if (preg_match('/\(([A-Z]{1,4}(?:[-–][A-Z]{1,4})?(?:\s+Series)?)\)\s*$/u', $title, $m)) {
            return $m[1];
        }

        /* "… VE" */
        if (preg_match('/\s([A-Z]{1,4}(?:[-–][A-Z]{1,4})?)\s*$/u', $title, $m)) {
            return $m[1];
        }

        return '';
    }

    /**
     * Build the English meta description for the current request.
     *
     * @return string Empty when no context could be determined.
     */
    private static function en_description_fallback() {
        if (is_singular('news')) {
            $name = get_the_title();

            /* The article's own excerpt is the best summary — but only
             * when it is actually English. The older English articles
             * were translated before the excerpt was carried over, so
             * some of them still hold Chinese. */
            $excerpt = trim((string) get_post_field('post_excerpt', get_the_ID()));
            if ($excerpt !== '' && !self::has_cjk($excerpt)) {
                return $excerpt;
            }

            return trim(sprintf(
                '%s — a practical guide from Gengwen Electric on electrical connectors and crimp terminals. Technical detail, standards and factory know-how for buyers and engineers. Factory direct supply, 1-hour quotation.',
                $name
            ));
        }

        if (is_singular('product')) {
            $name = get_the_title();

            /* The model code is recovered from the TITLE, not from the
             * `model` meta — that field holds the Chinese type
             * description ("TL型"), which would leak Chinese into the
             * English description, and `model_en` holds the English
             * type description, which would repeat the title. */
            $model = self::model_code_from_title($name);

            /* Only add the code when the title does not already carry
             * it — "DT-25 …" must not become "DT-25 … (DT-25)". */
            if ($model !== '' && stripos($name, $model) !== false) {
                $model = '';
            }

            return trim(sprintf(
                '%s%s from Gengwen Electric — a direct manufacturer of electrical connectors and terminals. Tinned copper, CE / RoHS / ISO9001 certified, factory direct supply with 1-hour quotation.',
                $name,
                $model ? ' (' . $model . ')' : ''
            ));
        }

        if (is_tax() || is_category() || is_tag()) {
            $term = get_queried_object();
            $name = is_object($term) ? $term->name : '';
            return trim(sprintf(
                '%s — copper lugs, crimp terminals and pre-insulated terminals manufactured and supplied directly by Gengwen Electric. CE / RoHS / ISO9001 certified, ready to ship, OEM / ODM welcome.',
                $name
            ));
        }

        if (is_post_type_archive('product')) {
            $cat = function_exists('xxdq_catalogue_kw') ? xxdq_catalogue_kw() : '300';
            return 'Gengwen Electric manufactures copper lugs, crimp terminals, pre-insulated terminals, connectors and wire-end accessories. ' . $cat . '+ models in stock, CE / RoHS / ISO9001 certified, factory direct supply, 1-hour quotation.';
        }

        if (is_post_type_archive('news')) {
            return 'Selection guides, crimping standards and factory news for electrical connectors and terminals from Gengwen Electric.';
        }

        /* Pages. NOTE: `is_page()` is FALSE on the English site —
         * the router resolves pages through `p=` instead of `page_id=`,
         * so WordPress treats them as a generic singular. We therefore
         * test the post type directly. */
        if (is_singular('page')) {
            $name = get_the_title();
            /* Prefer the page's own excerpt when it has one. */
            $excerpt = trim((string) get_post_field('post_excerpt', get_the_ID()));
            if ($excerpt !== '' && !self::has_cjk($excerpt)) {
                return $excerpt;
            }
            return trim(sprintf(
                '%s — Gengwen Electric, a direct manufacturer of electrical connectors and terminals in Yueqing, China. CE / RoHS / ISO9001 certified, factory direct supply, 1-hour quotation.',
                $name
            ));
        }

        if (is_front_page() || is_home()) {
            $cat = function_exists('xxdq_catalogue_kw') ? xxdq_catalogue_kw() : '300';
            return 'Gengwen Electric manufactures copper lugs, crimp terminals, pre-insulated terminals and electrical connectors. ' . $cat . '+ models in stock, CE / RoHS / ISO9001 certified, 24-hour dispatch, 1-hour quotation. OEM / ODM welcome.';
        }

        return '';
    }

    /**
     * Replace a stale hardcoded catalogue size with the real one.
     *
     * The marketing copy used to claim "500+ 规格" / "600+ Models"
     * while the catalogue held far fewer products — a claim any buyer
     * could disprove by counting the product list. The number now comes
     * from the database (xxdq_catalogue_stats()), so it can never drift.
     *
     * This runs on the final rendered title / description of BOTH
     * languages, because the stale value is stored per page in the
     * Yoast post meta and would otherwise survive every code change.
     *
     * @param string $text The rendered text.
     * @return string
     */
    public static function refresh_catalogue_count($text) {
        if (!is_string($text) || $text === '') {
            return $text;
        }
        if (!function_exists('xxdq_catalogue_kw')) {
            return $text;
        }
        if (!preg_match('/(?:500|600)\s*\+/u', $text)) {
            return $text;
        }

        $cat = xxdq_catalogue_kw();

        /* "600+规格" / "600+ 规格" / "600+ models" / "600+ Models" */
        $text = preg_replace('/(?:500|600)\s*\+\s*规格/u', $cat . '+ 规格', $text);
        /* "Models" keeps its capital only when it starts a clause —
         * "297+ Models in stock" reads wrong mid-sentence. */
        $text = preg_replace('/(?:500|600)\s*\+\s*Models(?=\s+(?:in|for|and|,|\.|$))/u', $cat . '+ models', $text);
        $text = preg_replace('/(?:500|600)\s*\+\s*Models/u', $cat . '+ Models', $text);
        $text = preg_replace('/(?:500|600)\s*\+\s*models/u', $cat . '+ models', $text);
        $text = preg_replace('/(?:500|600)\s*\+\s*units ready to ship,?/u', '', $text);
        $text = preg_replace('/(?:500|600)\s*\+\s*库存,?/u', '', $text);

        /* Tidy up the double separators the removals may have left. */
        $text = preg_replace('/\s*,\s*,\s*/u', ', ', $text);
        $text = preg_replace('/\.\s*\./u', '.', $text);

        return $text;
    }

    /**
     * Rewrite the FINAL rendered <title> on the English site.
     *
     * Yoast resolves the template against the indexable row and caches
     * the result. For taxonomy archives the indexable stores a title
     * that was rendered with the CHINESE template, so filtering
     * `wpseo_titles` alone is not enough — the cached value wins.
     *
     * This filter runs last (priority 40, after Yoast and after the
     * theme's own wpseo_title filters) and replaces any Chinese
     * fragments that leaked into the English title.
     */
    public static function filter_final_title($title) {
        /* First: replace any stale hardcoded catalogue size with the
         * real one, in whichever language the title is written. */
        $title = self::refresh_catalogue_count($title);

        if (!XXDQ_I18n::is_en()) {
            return $title;
        }
        if (!is_string($title) || $title === '') {
            return $title;
        }

        /* If the title is already free of Chinese, leave it alone —
         * that covers products and pages whose title is the English
         * post title. */
        if (!preg_match('/[\x{4e00}-\x{9fff}]/u', $title)) {
            return $title;
        }

        /* Taxonomy / archive: rebuild from the English term name. */
        if (is_tax() || is_category() || is_tag()) {
            $term = get_queried_object();
            if (is_object($term)) {
                $en_name = class_exists('XXDQ_I18n_Content')
                    ? XXDQ_I18n_Content::term_text($term, 'name')
                    : $term->name;
                if ($en_name && !preg_match('/[\x{4e00}-\x{9fff}]/u', $en_name)) {
                    return $en_name . ' - Manufacturer | Gengwen Electric';
                }
            }
        }

        if (is_post_type_archive('product')) {
            return 'Electrical Connectors & Terminals - Manufacturer | Gengwen Electric';
        }
        if (is_post_type_archive('news')) {
            return 'News & Industry Insights | Gengwen Electric';
        }

        /* Last resort: strip the Chinese tail that follows the first
         * separator and append the English brand. */
        $parts = preg_split('/\s*[-–—|]\s*/u', $title, 2);
        $head  = trim($parts[0]);
        if ($head !== '' && !preg_match('/[\x{4e00}-\x{9fff}]/u', $head)) {
            return $head . ' | Gengwen Electric';
        }

        return $title;
    }

    /**
     * Force the Open Graph / Twitter title to the plain product name.
     *
     * Yoast's `social-title-product` template would otherwise append
     * the Chinese site name on the English site.
     */
    public static function filter_social_title($title) {
        if (!XXDQ_I18n::is_en()) {
            return $title;
        }
        if (is_singular('product') || is_singular('post')) {
            return get_the_title();
        }
        return $title;
    }

    /**
     * Scrub the Chinese site name out of the social titles.
     *
     * Yoast's OG title template is `%%title%% %%sitename%%`, and the
     * site name comes from the WordPress option (the Chinese legal
     * name). The English site must not leak it into the social card.
     *
     * @param string $title The social title.
     * @return string
     */
    public static function scrub_social_title($title) {
        if (!XXDQ_I18n::is_en()) {
            return $title;
        }
        if (!is_string($title) || $title === '') {
            return $title;
        }

        /* The brand name to append. */
        $brand = XXDQ_I18n::t('brand.name');

        /* Drop the Chinese site name / tagline wherever it appears. */
        $title = str_replace(
            [get_bloginfo('name'), get_bloginfo('description')],
            ['', ''],
            $title
        );

        /* Collapse the leftover separators. */
        $title = preg_replace('/\s*[-–—|]\s*[-–—|]\s*/u', ' - ', $title);
        $title = preg_replace('/\s*[-–—|]\s*$/u', '', $title);
        $title = preg_replace('/^[-–—|]\s*/u', '', $title);
        $title = trim((string) $title);

        if ($title === '') {
            return $brand;
        }

        /* If the title still contains Chinese, rebuild it from the
         * page context rather than shipping mixed-language text. */
        if (self::has_cjk($title)) {
            return self::en_social_title_fallback();
        }

        return $title . ' | ' . $brand;
    }

    /**
     * Build a clean English social title for the current request.
     *
     * @return string
     */
    private static function en_social_title_fallback() {
        $brand = XXDQ_I18n::t('brand.name');

        if (is_singular()) {
            return get_the_title() . ' | ' . $brand;
        }
        if (is_tax() || is_category() || is_tag()) {
            $term = get_queried_object();
            if (is_object($term)) {
                $name = class_exists('XXDQ_I18n_Content')
                    ? XXDQ_I18n_Content::term_text($term, 'name')
                    : $term->name;
                if ($name && !self::has_cjk($name)) {
                    return $name . ' - Manufacturer | ' . $brand;
                }
            }
        }
        if (is_post_type_archive('product')) {
            return 'Electrical Connectors & Terminals | ' . $brand;
        }
        if (is_post_type_archive('news')) {
            return 'News & Industry Insights | ' . $brand;
        }
        if (is_front_page() || is_home()) {
            return 'Electrical Connector Manufacturer | ' . $brand;
        }
        return $brand;
    }

    /**
     * Ensure the Open Graph description is English too.
     *
     * Yoast resolves the OG description from the same (cached Chinese)
     * indexable row, so it can carry Chinese text into the English
     * site. Any Chinese OG description is replaced with the English
     * fallback so the social card matches the page.
     *
     * An EMPTY OG description is replaced as well — Yoast emits no
     * `og:description` at all when its template resolves to nothing,
     * which leaves the English social card without a summary.
     *
     * @param string $description The OG description.
     * @return string
     */
    public static function ensure_og_description($description) {
        if (!XXDQ_I18n::is_en()) {
            return $description;
        }
        if (!self::has_cjk($description) && trim((string) $description) !== '') {
            /* Taxonomy archives: the raw term description is a long
             * machine-style product blurb. The meta description built
             * from the page context is far better for a social card. */
            if (is_tax() || is_category() || is_tag()) {
                $fallback = self::en_description_fallback();
                if ($fallback !== '') {
                    return $fallback;
                }
            }
            return $description;
        }
        $fallback = self::en_description_fallback();
        return $fallback !== '' ? $fallback : $description;
    }

    /**
     * Scrub Chinese out of the Yoast JSON-LD graph.
     *
     * Yoast's WebPage / CollectionPage pieces copy the *cached* title and
     * description of the shared indexable row, so on the English site they
     * still carry the Chinese product-archive title ("产品 - 全系列现货 国标规格
     * | 耕文电气"). The `<title>` tag is already fixed by
     * `filter_final_title()`, but the schema graph is a separate output.
     *
     * @param array $graph The Yoast schema graph.
     * @return array
     */
    public static function filter_schema_graph($graph) {
        if (!XXDQ_I18n::is_en()) {
            return $graph;
        }
        if (!is_array($graph)) {
            return $graph;
        }

        $fallback = self::en_description_fallback();
        $brand    = XXDQ_I18n::t('brand.name');

        foreach ($graph as $i => $piece) {
            if (!is_array($piece)) {
                continue;
            }

            /* `name` — the page title as Yoast resolved it. */
            if (isset($piece['name']) && self::has_cjk($piece['name'])) {
                $piece['name'] = self::en_schema_title($piece['name']);
            }

            /* `description` — the page description as Yoast resolved it. */
            if (isset($piece['description']) && self::has_cjk($piece['description'])) {
                $piece['description'] = $fallback !== ''
                    ? $fallback
                    : self::en_schema_description($piece['description']);
            }

            /* `alternateName` — the Chinese brand. */
            if (isset($piece['alternateName']) && self::has_cjk($piece['alternateName'])) {
                $piece['alternateName'] = $brand;
            }

            /* `caption` on the logo image. */
            if (isset($piece['caption']) && self::has_cjk($piece['caption'])) {
                $piece['caption'] = $brand;
            }

            /* Breadcrumb items — the crumbs Yoast built. */
            if (isset($piece['itemListElement']) && is_array($piece['itemListElement'])) {
                foreach ($piece['itemListElement'] as $j => $item) {
                    if (is_array($item) && isset($item['name']) && self::has_cjk($item['name'])) {
                        $item['name'] = self::en_crumb_label($item['name']);
                        $piece['itemListElement'][$j] = $item;
                    }
                }
            }

            $graph[$i] = $piece;
        }

        return $graph;
    }

    /**
     * Build an English title for a schema piece that still has Chinese.
     *
     * @param string $title The Chinese title.
     * @return string
     */
    private static function en_schema_title($title) {
        $brand = XXDQ_I18n::t('brand.name');

        if (is_post_type_archive('product')) {
            return 'Electrical Connectors & Terminals - Manufacturer | ' . $brand;
        }
        if (is_post_type_archive('news')) {
            return 'News & Industry Insights | ' . $brand;
        }
        if (is_tax() || is_category() || is_tag()) {
            $term = get_queried_object();
            if (is_object($term) && !self::has_cjk($term->name)) {
                return $term->name . ' - Manufacturer | ' . $brand;
            }
        }
        if (is_singular()) {
            $t = get_the_title();
            if ($t !== '' && !self::has_cjk($t)) {
                return $t . ' | ' . $brand;
            }
        }

        /* Keep the leading part that is already English. */
        $parts = preg_split('/\s*[-–—|]\s*/u', $title, 2);
        $head  = trim($parts[0]);
        if ($head !== '' && !self::has_cjk($head)) {
            return $head . ' | ' . $brand;
        }

        return $brand;
    }

    /**
     * Build an English description for a schema piece that still has Chinese.
     *
     * @param string $description The Chinese description.
     * @return string
     */
    private static function en_schema_description($description) {
        $fallback = self::en_description_fallback();
        return $fallback !== '' ? $fallback : 'Electrical connectors and terminals manufactured by Gengwen Electric.';
    }

    /**
     * Translate a Chinese breadcrumb label into English.
     *
     * @param string $label The Chinese label.
     * @return string
     */
    private static function en_crumb_label($label) {
        $map = [
            '首页'   => 'Home',
            '产品中心' => 'Products',
            '新闻中心' => 'News',
            '产品'   => 'Products',
            '新闻'   => 'News',
        ];
        if (isset($map[$label])) {
            return $map[$label];
        }

        /* Strip a Chinese brand tail and keep the English remainder. */
        $label = str_replace(
            [get_bloginfo('name'), get_bloginfo('description')],
            '',
            $label
        );
        $label = trim((string) preg_replace('/\s*[-–—|]\s*[-–—|]?\s*$/u', '', $label));
        if ($label !== '' && !self::has_cjk($label)) {
            return $label;
        }

        return XXDQ_I18n::t('nav.home');
    }
}

